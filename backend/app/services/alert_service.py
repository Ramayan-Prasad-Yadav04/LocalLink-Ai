import smtplib
from email.message import EmailMessage
from datetime import datetime
from typing import List, Optional, Dict, Any
from ..config import settings
import logging

logger = logging.getLogger("floodwatch.alerts")

class AutomatedAlertService:
    """
    Automated Multi-Channel Alert & Notification Dispatcher.
    
    Features:
      - Escalation-triggered alerts.
      - SMTP Email broadcast to emergency responders.
      - Throttling & deduplication to prevent alert fatigue.
    """

    def __init__(self):
        self.last_sent_risk: Optional[str] = None
        self.last_sent_timestamp: Optional[datetime] = None
        self.throttle_seconds: int = 45  # Don't resend identical alerts within 45s

    def should_trigger_alert(self, new_risk_level: str) -> bool:
        """Determines if an alert should be dispatched based on risk level and throttling."""
        if new_risk_level in ("HIGH", "CRITICAL"):
            if self.last_sent_risk != new_risk_level:
                return True
            if self.last_sent_timestamp:
                delta = (datetime.utcnow() - self.last_sent_timestamp).total_seconds()
                if delta > self.throttle_seconds:
                    return True
        return False

    def dispatch_alert(
        self,
        risk_level: str,
        affected_location: str,
        flood_probability: float,
        recommended_action: str,
        recipients: Optional[List[str]] = None
    ) -> Dict[str, Any]:
        """
        Constructs and dispatches alert message via email and internal audit logs.
        """
        target_recipients = recipients or settings.DEFAULT_ALERT_RECIPIENTS
        title = f"[{risk_level}] FLASH FLOOD WARNING: {affected_location}"
        
        body = f"""
===========================================================
FLOODWATCH AI – EMERGENCY DISASTER MANAGEMENT ALERT
===========================================================
Severity Level   : {risk_level}
Affected Basin   : {affected_location}
Flood Probability: {flood_probability:.1f}%
Timestamp (UTC)  : {datetime.utcnow().isoformat()}

ACTIONABLE DIRECTIVE:
{recommended_action}

CRITICAL INFRASTRUCTURE NOTICE:
Lowland gorge river bridges and drainage channels may be inundated.
Refer to FloodWatch AI Evacuation Routing for Dijkstra-calculated safe paths.

Emergency Hotlines:
- NDRF Disaster Command: 1078
- SDRF Control Center  : 1070
- National Emergency   : 112
===========================================================
This is an automated decision support message generated by FloodWatch AI.
"""

        email_success = self._send_email(
            subject=title,
            body=body,
            recipients=target_recipients
        )

        self.last_sent_risk = risk_level
        self.last_sent_timestamp = datetime.utcnow()

        return {
            "title": title,
            "message": body.strip(),
            "risk_level": risk_level,
            "affected_location": affected_location,
            "flood_probability": flood_probability,
            "action_required": recommended_action,
            "email_sent": email_success,
            "siren_triggered": (risk_level == "CRITICAL"),
            "timestamp": datetime.utcnow().isoformat()
        }

    def _send_email(self, subject: str, body: str, recipients: List[str]) -> bool:
        """Sends email via SMTP or records simulation log if unconfigured."""
        if not settings.SMTP_ENABLED or not settings.SMTP_USERNAME or not settings.SMTP_PASSWORD:
            logger.info(
                f"[SMTP Simulation] Alert generated for {recipients}. Subject: {subject} (SMTP credentials not configured in .env - simulated broadcast successfully logged)"
            )
            return True

        try:
            msg = EmailMessage()
            msg["Subject"] = subject
            msg["From"] = settings.ALERT_SENDER_EMAIL
            msg["To"] = ", ".join(recipients)
            msg.set_content(body)

            with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT) as server:
                server.starttls()
                server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
                server.send_message(msg)

            logger.info(f"Successfully transmitted email alert to {recipients}")
            return True

        except Exception as e:
            logger.error(f"Failed to dispatch SMTP email: {str(e)}")
            return False

alert_service = AutomatedAlertService()
